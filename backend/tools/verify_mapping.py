#!/usr/bin/env python3
"""Is the Yosys/OpenSTA estimate about the right circuit, and are its numbers right?

    cd backend
    PATH="$HOME/.local/bin:$PATH" python3 tools/verify_mapping.py            # the 5 built-in + every saved evaluation design
    PATH="$HOME/.local/bin:$PATH" python3 tools/verify_mapping.py c3 counter  # only some

For each design, three independent checks (none of them reads the number it is checking from the same place):

  1. Gate-level simulation. Yosys writes behavioural models of the sky130 cells straight from the liberty
     file; the mapped netlist is simulated in Icarus with the SAME testbench as the RTL and must give the
     same Passed/Failed counts. This is what shows the netlist computes what the RTL computes.
  2. Area recount. Area and cell count are recomputed from the written netlist and the liberty file and
     compared with what timing.run_timing reported (which comes from Yosys' `stat`).
  3. Timing sanity. slack = period - arrival is re-derived: the same design is timed at a second target
     clock and the implied minimum period (period - slack) must not change.

A design the estimate refuses on purpose (latches, tri-states, derived clocks ...) is reported as such and
is not a failure; one that should have been mapped but was not is.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))

import offline_designs as od  # noqa: E402
import timing  # noqa: E402

ARTIFACTS = BACKEND / "evaluation" / "artifacts"


# --------------------------------------------------------------------------- helpers
def declared_modules(rtl: str) -> List[str]:
    return re.findall(r"^\s*module\s+(\w+)", rtl, re.M)


def top_module(rtl: str, tb: str) -> Optional[str]:
    """The module the testbench instantiates (an RTL module name followed by `[#(...)] instance (`)."""
    for m in declared_modules(rtl):
        if re.search(rf"\b{re.escape(m)}\b\s*(?:#\s*\(.*?\)\s*)?\w+\s*\(", tb, re.S):
            return m
    return None


def strip_parameter_overrides(tb: str, module: str) -> str:
    """Remove `#( ... )` after the module name: the mapped netlist already has its parameters applied."""
    m = re.search(rf"\b{re.escape(module)}\s*#\s*\(", tb)
    if not m:
        return tb
    depth, i = 1, m.end()
    while i < len(tb) and depth:
        depth += (tb[i] == "(") - (tb[i] == ")")
        i += 1
    return tb[:m.start() + len(module)] + " " + tb[i:] if depth == 0 else tb


def liberty_areas() -> Dict[str, float]:
    text = timing.LIBERTY.read_text()
    heads = list(re.finditer(r'cell\s*\(\s*"?(sky130_fd_sc_hd__\w+)"?\s*\)\s*\{', text))
    areas: Dict[str, float] = {}
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        a = re.search(r"\barea\s*:\s*([0-9.]+)", text[m.end():end])   # `area` can sit thousands of characters in
        if a:
            areas[m.group(1)] = float(a.group(1))
    return areas


def netlist_totals(netlist: str, areas: Dict[str, float]) -> Tuple[float, int]:
    cells = re.findall(r"^\s*(sky130_fd_sc_hd__\w+)\s+\S+\s*\($", netlist, re.M)
    unknown = [c for c in cells if c not in areas]
    if unknown:
        raise KeyError(f"cell not in the liberty file: {unknown[0]}")
    return round(sum(areas[c] for c in cells), 3), len(cells)


def build_cell_models(dest: Path) -> Path:
    """Behavioural Verilog models of every sky130 cell, generated by Yosys from the liberty file."""
    out = dest / "sky130_cells.v"
    script = (f'read_liberty -ignore_miss_func -ignore_miss_dir -ignore_miss_data_latch "{timing.LIBERTY}"; '
              f'write_verilog -noattr {out.name}')
    p = subprocess.run(["yosys", "-q", "-p", script], cwd=str(dest), capture_output=True, text=True, timeout=120,
                       stdin=subprocess.DEVNULL, env=timing._env())
    if not out.exists():
        raise RuntimeError("could not build cell models: " + (p.stderr or p.stdout)[-200:])
    return out


def verdict(output: str) -> Optional[Tuple[int, int]]:
    p = re.search(r"^Passed:\s*(\d+)", output, re.M)
    f = re.search(r"^Failed:\s*(\d+)", output, re.M)
    return (int(p.group(1)), int(f.group(1))) if p and f else None


def simulate(files: List[Path], cwd: Path, tag: str):
    vvp = cwd / f"{tag}.vvp"
    c = subprocess.run(["iverilog", "-g2012", "-o", str(vvp)] + [str(f) for f in files], cwd=str(cwd),
                       capture_output=True, text=True, timeout=120, stdin=subprocess.DEVNULL)
    if c.returncode:
        return "compile error: " + c.stderr.strip().splitlines()[0][:120] if c.stderr.strip() else "compile error"
    r = subprocess.run(["vvp", "-n", str(vvp)], cwd=str(cwd), capture_output=True, text=True, timeout=300,
                       stdin=subprocess.DEVNULL)
    return verdict(r.stdout) or "no Passed/Failed line"


# --------------------------------------------------------------------------- one design
def check_design(name: str, rtl: str, tb: str, models: Path, areas: Dict[str, float], work: Path) -> dict:
    """Run the three checks. Returns {name, status, detail}; status is OK, REFUSED or FAIL."""
    top = top_module(rtl, tb)
    if top is None:
        return {"name": name, "status": "FAIL", "detail": "could not find which module the testbench instantiates"}
    wd = work / name
    wd.mkdir(parents=True, exist_ok=True)
    r = timing.run_timing(rtl, top, wd / "map", 100, testbench_code=tb)
    refused = r.slack_ns is None
    netlist_path = wd / "map" / "netlist.v"
    if refused and "could not be mapped" in (r.error or ""):
        return {"name": name, "status": "FAIL", "detail": r.error[:140]}
    if refused and not netlist_path.exists():
        return {"name": name, "status": "REFUSED", "detail": (r.error or "")[:110]}

    (wd / "design.sv").write_text(rtl)
    (wd / "tb.sv").write_text(tb)
    (wd / "tb_gate.sv").write_text(strip_parameter_overrides(tb, top))
    problems: List[str] = []

    # 1. gate-level simulation against the RTL simulation
    rtl_v = simulate([wd / "design.sv", wd / "tb.sv"], wd, "rtl")
    gate_v = simulate([netlist_path, models, wd / "tb_gate.sv"], wd, "gate")
    if not (isinstance(rtl_v, tuple) and isinstance(gate_v, tuple) and rtl_v == gate_v and rtl_v[1] == 0):
        problems.append(f"gate-level simulation differs: RTL {rtl_v}, mapped netlist {gate_v}")

    # 2. area recount from the netlist and the liberty file
    if r.area_um2 is not None:
        try:
            area, cells = netlist_totals(netlist_path.read_text(), areas)
            if abs(area - r.area_um2) > 0.01 or cells != r.cell_count:
                problems.append(f"area/cells reported {r.area_um2}/{r.cell_count}, recounted {area}/{cells}")
        except KeyError as e:
            problems.append(str(e))

    # 3. the implied minimum period must not depend on the target asked for
    if not refused:
        r2 = timing.run_timing(rtl, top, wd / "map2", 500, testbench_code=tb)
        if r2.slack_ns is None:
            problems.append("second timing run at 500 MHz gave no result")
        else:
            a, b = r.period_ns - r.slack_ns, r2.period_ns - r2.slack_ns
            if abs(a - b) > 0.0005:
                problems.append(f"minimum period changed with the target: {a:.4f} ns vs {b:.4f} ns")

    if problems:
        return {"name": name, "status": "FAIL", "detail": "; ".join(problems)}
    sim = f"{rtl_v[0]} checks, same on RTL and gates"
    if refused:
        return {"name": name, "status": "REFUSED", "detail": f"{sim}; not timed: {(r.error or '')[:80]}"}
    return {"name": name, "status": "OK", "detail": f"{sim}; {r.area_um2:g} um^2 / {r.cell_count} cells; "
                                                   f"min period {r.period_ns - r.slack_ns:.3f} ns"}


def collect(only: List[str]) -> List[Tuple[str, str, str]]:
    items: List[Tuple[str, str, str]] = []
    for design in sorted(ARTIFACTS.glob("*_design.sv")):
        pid = design.name.split("_")[0]
        tb = ARTIFACTS / f"{pid}_testbench.sv"
        if tb.exists():
            items.append((pid, design.read_text(), tb.read_text()))
    for key, d in od.DESIGNS.items():
        items.append((f"builtin-{key}", d["rtl"], d["tb"]))
    return [i for i in items if not only or i[0] in only or i[0].replace("builtin-", "") in only]


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("only", nargs="*", help="design ids to check (default: all)")
    args = ap.parse_args(argv)
    missing = timing.missing_requirements()
    if missing:
        print("Cannot run: missing " + ", ".join(missing))
        return 2
    items = collect(args.only)
    if not items:
        print("No designs selected.")
        return 2
    areas = liberty_areas()
    bad = 0
    with tempfile.TemporaryDirectory() as td:
        work = Path(td)
        models = build_cell_models(work)
        for name, rtl, tb in items:
            res = check_design(name, rtl, tb, models, areas, work)
            bad += res["status"] == "FAIL"
            print(f"{res['name']:16s} {res['status']:8s} {res['detail']}", flush=True)
    print(f"\n{len(items)} design(s) checked, {bad} failure(s).")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
